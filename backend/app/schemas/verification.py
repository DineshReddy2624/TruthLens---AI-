"""Pydantic schemas for claim extraction, analysis, verification, RAG, and reporting API."""

from pydantic import BaseModel, Field
from datetime import datetime
from typing import Any
from app.models.verification import InputType, RequestStatus, VerdictLabel


# --- Agent Schemas ---

class ExtractedEntity(BaseModel):
    """An entity identified within a claim."""
    name: str = Field(..., description="Name of the entity")
    category: str = Field(
        ...,
        description="Category: person, organization, location, date, number, other",
    )


class ExtractedClaimItem(BaseModel):
    """A single standalone factual claim with extracted entities."""
    claim_text: str = Field(..., description="Standalone, unambiguous factual claim")
    entities: list[ExtractedEntity] = Field(
        default_factory=list, description="Entities found in this claim"
    )


class ClaimExtractionOutput(BaseModel):
    """Structured output from the Claim Extraction Agent."""
    claims: list[ExtractedClaimItem] = Field(
        default_factory=list, description="List of extracted factual claims"
    )


class ClaimAnalysisOutput(BaseModel):
    """Structured output from the Claim Analysis Agent."""
    claim_type: str = Field(
        ...,
        description="statistical, scientific, historical, political, other",
    )
    topic: str = Field(..., description="Topic or domain of the claim")
    is_time_sensitive: bool = Field(
        ..., description="Whether truth value depends on a timeframe"
    )
    time_context: str | None = Field(
        None, description="Year, date, or timeframe if time-sensitive"
    )
    support_criteria: str = Field(
        ..., description="What evidence would prove this claim"
    )
    contradict_criteria: str = Field(
        ..., description="What evidence would disprove this claim"
    )
    is_checkable: bool = Field(
        ..., description="Whether the claim can be empirically verified"
    )
    uncheckable_reason: str | None = Field(
        None, description="Reason if claim is uncheckable"
    )


class GeneratedQueryItem(BaseModel):
    """A search query generated by the Research Agent."""
    query_text: str = Field(..., description="Targeted web search query string")
    intent: str = Field(..., description="Query search intent: 'support' or 'contradict'")


class ResearchAgentOutput(BaseModel):
    """Structured output from the Research Agent."""
    queries: list[GeneratedQueryItem] = Field(
        ...,
        description="4 targeted search queries (2 support-seeking, 2 contradict-seeking)",
    )


class RetrievedPassageItem(BaseModel):
    """A passage retrieved and reranked as evidence."""
    passage_id: int | None = None
    source_id: int | None = None
    url: str
    title: str
    domain: str
    published_at: datetime | None = None
    passage: str
    rank_score: float
    bm25_score: float | None = None
    dense_score: float | None = None


class SourceEvaluationOutput(BaseModel):
    """Output from the Source Evaluation Agent."""
    publisher_score: float = Field(..., ge=0.0, le=2.0)
    date_score: float = Field(..., ge=0.0, le=2.0)
    quality_score: float = Field(..., ge=0.0, le=2.0)
    corroboration_score: float = Field(..., ge=0.0, le=2.0)
    total_score: float = Field(..., ge=0.0, le=8.0)
    reason: str = Field(...)


class FactVerificationOutput(BaseModel):
    """Output from the Fact Verification Agent."""
    label: str = Field(..., description="Supported | Contradicted | Partially Supported | Insufficient Evidence | Conflicting Evidence")
    key_passage_ids: list[int] = Field(default_factory=list)
    missing_context: str | None = None
    reasoning: str | None = None


class ConflictItem(BaseModel):
    """An individual contradiction or discrepancy."""
    type: str
    source_a: str
    value_a: str
    source_b: str
    value_b: str
    explanation: str


class ContradictionDetectionOutput(BaseModel):
    """Output from the Contradiction Detection Agent."""
    has_conflicts: bool = False
    conflicts: list[dict[str, Any]] = Field(default_factory=list)
    conflict_explanation: str | None = None


class ExplanationOutput(BaseModel):
    """Output from the Explanation Agent."""
    explanation: str
    citations_used: list[int] = Field(default_factory=list)


# --- API Request & Response Schemas ---

class SubmitTextRequest(BaseModel):
    """Submit raw text or single claim for verification."""
    text: str = Field(..., min_length=5, max_length=100_000, description="Claim or article text")
    input_type: InputType = Field(default=InputType.claim)


class SubmitUrlRequest(BaseModel):
    """Submit a URL for verification."""
    url: str = Field(..., min_length=10, max_length=2048, description="Web page URL to verify")


class SourceEvaluationResponse(BaseModel):
    """Source credibility evaluation breakdown."""
    id: int
    source_id: int
    publisher_score: float
    date_score: float
    quality_score: float
    corroboration_score: float
    total_score: float
    reason: str | None = None

    model_config = {"from_attributes": True}


class RetrievedSourceResponse(BaseModel):
    """Source domain and title metadata."""
    id: int
    url: str
    domain: str | None = None
    title: str | None = None
    publisher: str | None = None
    published_at: datetime | None = None
    evaluation: SourceEvaluationResponse | None = None

    model_config = {"from_attributes": True}


class EvidenceRecordResponse(BaseModel):
    """Retrieved passage and NLI evaluation."""
    id: int
    source_id: int
    passage: str
    nli_label: str | None = None
    nli_scores: dict[str, Any] | None = None
    rank_score: float | None = None

    model_config = {"from_attributes": True}


class VerificationResultResponse(BaseModel):
    """Verification result for a claim."""
    id: int
    label: str
    confidence: float
    key_passage_ids: list[int] | None = None
    missing_context: str | None = None
    conflicts: dict[str, Any] | None = None
    explanation: str | None = None
    created_at: datetime

    model_config = {"from_attributes": True}


class ExtractedClaimResponse(BaseModel):
    """Details of an extracted claim."""
    id: int
    claim_text: str
    claim_type: str | None = None
    entities: list[dict[str, Any]] | None = None
    analysis: dict[str, Any] | None = None
    result: VerificationResultResponse | None = None
    sources: list[RetrievedSourceResponse] = []
    evidence_records: list[EvidenceRecordResponse] = []
    created_at: datetime

    model_config = {"from_attributes": True}


class VerificationRequestResponse(BaseModel):
    """Summary of a verification request."""
    id: int
    user_id: int
    input_type: str
    status: str
    source_url: str | None = None
    claims_count: int = 0
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class VerificationDetailResponse(BaseModel):
    """Full detail of a verification request with all claims and analysis."""
    id: int
    user_id: int
    input_type: str
    status: str
    source_url: str | None = None
    raw_text_preview: str | None = None
    claims: list[ExtractedClaimResponse] = []
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class RAGChatRequest(BaseModel):
    """Ask a question about a verified document."""
    request_id: int
    message: str = Field(..., min_length=2, max_length=1000)


class RAGChatResponse(BaseModel):
    """Answer with evidence citations and confidence."""
    answer: str
    citations_used: list[int] = Field(default_factory=list)
    citations_metadata: list[dict[str, Any]] = Field(default_factory=list)
    is_sufficient: bool = True


class ChatHistoryItem(BaseModel):
    """A chat message in the conversation history."""
    id: int
    role: str
    message: str
    citations: list[dict[str, Any]] | None = None
    created_at: datetime

    model_config = {"from_attributes": True}


class DashboardStatsResponse(BaseModel):
    """Aggregated statistics for the user dashboard."""
    total_requests: int
    total_claims: int
    label_distribution: dict[str, int]
    avg_confidence: float
    recent_activity: list[VerificationRequestResponse]
